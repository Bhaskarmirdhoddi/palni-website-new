import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'vendor')

// Preserve all independent reference IIFEs, including the outcome carousel.
for (const [file, name] of [['site', 'initSite'], ['scenes', 'initScenes']]) {
  const source = readFileSync(join(dir, `${file}.raw.js`), 'utf8')
  writeFileSync(join(dir, `${file}.js`), `/* Generated by scripts/wrap-vendor.mjs. */
import { createPageEffects } from './pageEffects'
export function ${name}() {
  const effects = createPageEffects()
  const { requestAnimationFrame, cancelAnimationFrame, requestIdleCallback,
    setTimeout, clearTimeout, setInterval, clearInterval,
    IntersectionObserver, ResizeObserver, MutationObserver, addEventListener } = effects.api
  effects.captureListeners(() => {
${source}
  })
  return effects.dispose
}
`)
}
console.log('Wrapped reference scripts with route-scoped effects')
